'use strict';
// model/presentation.json is the source of truth; ship the same data without an async fetch.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const data=read('model/presentation.json'),catalog=read('model/catalog.json');
assert.equal(data.version,1);assert.deepEqual(Object.keys(data.types).sort(),catalog.types.map(t=>t.id).sort());
for(const type of catalog.types){const p=data.types[type.id],ids=new Set(type.fields.map(f=>f.id));
  assert(p.name&&Array.isArray(p.summary_fields)&&Array.isArray(p.state_fields),type.id);
  for(const id of [...p.summary_fields,...p.state_fields])assert(ids.has(id),type.id+' unknown field '+id);
  for(const id of p.state_fields)assert(p.summary_fields.includes(id),type.id+' state omitted from summary '+id);
}
const file=path.join(root,'apps/desktop/ui/type-presentation-data.js');
const output="'use strict';\n// Generated by scripts/generate-presentation.cjs from model/presentation.json.\nconst PCScopeTypePresentationData="+JSON.stringify(data)+";\nif(typeof module!=='undefined'&&module.exports)module.exports=PCScopeTypePresentationData;\n";
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8'),output,'presentation bundle is stale');
else fs.writeFileSync(file,output);
console.log('presentation profiles: '+Object.keys(data.types).length);
